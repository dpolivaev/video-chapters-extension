const { loadView, loadSessionRepository } = require('../../test/helpers/view-environment');

describe('PopupView', () => {
  let environment;
  let view;
  let storedSettings;
  let settingsRepository;
  let sessions;
  let model;
  let transcript;

  beforeEach(() => {
    environment = loadView(__dirname, 'PopupView');
    model = new ModelId('gemini-2.5-pro', 'Gemini');
    transcript = new VideoTranscript(
      '0:00 Subtitle content', 'Video title', 'Video author',
      'https://youtube.com/watch?v=testid', 'en', 'English', true
    );
    storedSettings = { selectedModel: model.toJSON(), apiKey: '', openRouterApiKey: '' };
    settingsRepository = new SettingsRepository({
      getUserSettings: async () => storedSettings,
      setUserSettings: async settings => {
        storedSettings = settings;
      },
      getHistoryLimit: async () => undefined,
      setHistoryLimit: async () => {}
    });
    const SessionRepository = loadSessionRepository();
    sessions = new SessionRepository();
    environment.browser.runtime.sendMessage.mockImplementation(async request => {
      switch (request.action) {
        case 'saveSettings':
          await settingsRepository.saveSettings(request.settings);
          return { success: true };
        case 'loadSettings':
          return { success: true, data: await settingsRepository.loadSettings() };
        case 'getAllModels':
          return { success: true, data: [model.toJSON()] };
        case 'setSessionResults':
          sessions.fromSessionResults(request.results);
          return { success: true };
        case 'getSessionResults':
          return { success: true, results: sessions.toSessionResults(request.resultId) };
        case 'getResultsTabStatus':
          return { open: false };
        default:
          return { success: true };
      }
    });
    view = Object.create(environment.View.prototype);
    Object.assign(view, {
      settings: { ...storedSettings },
      modelIndex: new Map([[model.value, model]]),
      isProcessing: false,
      currentVideo: {
        title: transcript.title,
        author: transcript.author,
        url: transcript.videoUrl.toString(),
        processedContent: transcript.toProcessedContent(),
        videoTranscript: transcript,
        tabId: 7
      }
    });
    environment.elements.modelSelect.value = model.value;
    view.setupEventListeners();
  });

  test('remembers subtitles-only selection without changing the model', async () => {
    const checkbox = environment.elements.subtitlesOnlyCheckbox;
    expect(checkbox).toBeDefined();
    await view.loadSettings();
    expect(checkbox.checked).toBe(false);

    checkbox.checked = true;
    await checkbox.dispatch('change');

    expect(storedSettings.subtitlesOnly).toBe(true);
    expect(storedSettings.selectedModel).toEqual(model.toJSON());
    checkbox.checked = false;
    await view.loadSettings();
    expect(checkbox.checked).toBe(true);
    expect(environment.elements.modelSelect.value).toBe(model.value);

    checkbox.checked = false;
    await checkbox.dispatch('change');
    expect(storedSettings.subtitlesOnly).toBe(false);
    expect(storedSettings.selectedModel).toEqual(model.toJSON());
  });

  test('opens subtitles without requesting chapter generation', async () => {
    const { elements, browser, window } = environment;
    elements.subtitlesOnlyCheckbox.checked = true;
    elements.instructionsTextarea.value = 'Saved instructions';
    environment.window.instructionHistory = { saveInstruction: jest.fn() };
    view.updateGenerateButtonState();

    expect(elements.generateBtn.disabled).toBe(false);
    expect(elements.generateBtn.textContent).toBe('show_subtitles_button');
    await elements.generateBtn.dispatch('click');

    const results = sessions.getActiveSession().toSessionResults();
    expect(results).toMatchObject({
      status: 'subtitles_only', model: null, chapters: '', customInstructions: '',
      processedContent: { content: transcript.content, language: 'en', trackName: 'English', isAutoGenerated: true },
      videoMetadata: { title: transcript.title, author: transcript.author, url: transcript.videoUrl.toString() }
    });
    expect(browser.runtime.sendMessage).toHaveBeenCalledWith({
      action: 'openResultsTab', videoTabId: 7, videoUrl: transcript.videoUrl.toString(), resultId: results.resultId
    });
    expect(browser.runtime.sendMessage).not.toHaveBeenCalledWith(expect.objectContaining({ action: 'generateChapters' }));
    expect(environment.window.instructionHistory.saveInstruction).not.toHaveBeenCalled();
    expect(elements.instructionsTextarea.value).toBe('Saved instructions');
    expect(window.close).toHaveBeenCalled();
  });

  test('generates chapters when subtitles-only is unchecked', async () => {
    const { elements, browser } = environment;
    elements.subtitlesOnlyCheckbox.checked = false;
    view.updateGenerateButtonState();
    expect(elements.generateBtn.disabled).toBe(true);
    expect(elements.generateBtn.textContent).toBe('generate_chapters_button');

    await elements.generateBtn.dispatch('click');
    expect(browser.runtime.sendMessage).not.toHaveBeenCalledWith(expect.objectContaining({ action: 'generateChapters' }));

    elements.dynamicApiKeyInput.value = 'gemini-key';
    view.updateGenerateButtonState();
    expect(elements.generateBtn.disabled).toBe(false);
    await elements.generateBtn.dispatch('click');

    expect(browser.runtime.sendMessage).toHaveBeenCalledWith(expect.objectContaining({
      action: 'generateChapters', apiKey: 'gemini-key', modelId: model,
      processedContent: transcript.toProcessedContent()
    }));
  });

  test('reuses subtitles from an existing results page', async () => {
    const original = new ChapterGeneration(transcript, null, '', true);
    sessions.save(original);
    environment.browser.tabs.query.mockResolvedValue([{
      id: 8, url: 'moz-extension://test/results/results.html?resultId=' + original.id
    }]);
    await view.loadCurrentVideo();
    environment.elements.subtitlesOnlyCheckbox.checked = true;
    await environment.elements.generateBtn.dispatch('click');

    const results = sessions.getActiveSession().toSessionResults();
    expect(results.processedContent).toEqual(original.toSessionResults().processedContent);
    expect(results.videoMetadata).toMatchObject({ title: transcript.title, author: transcript.author });
    expect(environment.browser.runtime.sendMessage).not.toHaveBeenCalledWith(expect.objectContaining({ action: 'generateChapters' }));
  });

  test('preserves API keys and instructions when switching modes', async () => {
    storedSettings.apiKey = 'gemini-key';
    storedSettings.openRouterApiKey = 'openrouter-key';
    environment.elements.instructionsTextarea.value = 'Saved instructions';
    environment.elements.instructionNameInput.value = 'Instruction name';
    await view.loadSettings();

    environment.elements.subtitlesOnlyCheckbox.checked = true;
    await environment.elements.subtitlesOnlyCheckbox.dispatch('change');
    environment.elements.subtitlesOnlyCheckbox.checked = false;
    await environment.elements.subtitlesOnlyCheckbox.dispatch('change');

    expect(storedSettings.apiKey).toBe('gemini-key');
    expect(storedSettings.openRouterApiKey).toBe('openrouter-key');
    expect(environment.elements.dynamicApiKeyInput.value).toBe('gemini-key');
    expect(environment.elements.instructionsTextarea.value).toBe('Saved instructions');
    expect(environment.elements.instructionNameInput.value).toBe('Instruction name');
    expect(environment.elements.modelSelect.value).toBe(model.value);
  });

  test('requires available subtitles before opening results', async () => {
    environment.elements.subtitlesOnlyCheckbox.checked = true;
    view.currentVideo.processedContent = '';
    view.updateGenerateButtonState();
    expect(environment.elements.generateBtn.disabled).toBe(true);

    await environment.elements.generateBtn.dispatch('click');

    expect(environment.browser.runtime.sendMessage).not.toHaveBeenCalledWith(expect.objectContaining({ action: 'openResultsTab' }));
  });

  test('opens subtitles without an available model', async () => {
    environment.elements.subtitlesOnlyCheckbox.checked = true;
    view.modelIndex.clear();
    view.updateGenerateButtonState();
    expect(environment.elements.generateBtn.disabled).toBe(false);

    await environment.elements.generateBtn.dispatch('click');

    expect(sessions.getActiveSession().status).toBe('subtitles_only');
    expect(environment.window.close).toHaveBeenCalled();
  });

  test('does not open results when subtitle storage fails', async () => {
    environment.elements.subtitlesOnlyCheckbox.checked = true;
    environment.browser.runtime.sendMessage.mockResolvedValue({ success: false, error: 'Storage unavailable' });

    await environment.elements.generateBtn.dispatch('click');

    expect(environment.browser.runtime.sendMessage).not.toHaveBeenCalledWith(expect.objectContaining({ action: 'openResultsTab' }));
    expect(environment.window.close).not.toHaveBeenCalled();
  });
});
